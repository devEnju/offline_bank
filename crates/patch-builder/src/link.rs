//! The linker script of a payload: the same layout for every patch, with
//! the addresses of its program (`Contract`) and its router, the first entry
//! function its profile names. The checks of the ELF (`elf.rs`) and the
//! verifier hold the payload to it.

use crate::Profile;

/// The script for `profile`'s payload.
/// - The start-up hook goes into the zero bytes between the end of the
///   original text and the end of its last page.
/// - The payload goes on the first page after the original zero-initialised
///   data, allocated by the paired exheader.
/// - The table in `.patch.link_roots` keeps the entry functions in the link
///   (each patch's `src/link.rs`).
pub fn linker_script(profile: &Profile) -> String {
    let contract = profile.program.contract;
    let router = profile.entries()[0];
    format!(
        r#"/* {label}, the {kind} package: generated by patch-builder (link.rs). */
OUTPUT_FORMAT(elf32-littlearm)
OUTPUT_ARCH(arm)
ENTRY({router})

PHDRS {{
    bootstrap PT_LOAD FLAGS(5);
    payload_rx PT_LOAD FLAGS(5);
    payload_rw PT_LOAD FLAGS(6);
}}

__patch_original_app_init = {app_init:#010x};

SECTIONS {{
    . = {bootstrap:#010x};
    .patch.bootstrap : {{
        KEEP(*(.patch.bootstrap))
        KEEP(*(.patch.bootstrap.*))
    }} :bootstrap
    ASSERT(SIZEOF(.patch.bootstrap) > 0, "missing bootstrap")
    ASSERT(SIZEOF(.patch.bootstrap) <= {room:#x}, "bootstrap exceeds the zero bytes after the original text")

    . = {payload:#010x};
    __patch_payload_start = .;
    .text : {{
        FILL(0)
        *(.text .text.*)
        *(.rodata .rodata.*)
    }} :payload_rx
    .ARM.extab : {{ *(.ARM.extab .ARM.extab.*) }} :payload_rx
    .ARM.exidx : {{ *(.ARM.exidx .ARM.exidx.*) }} :payload_rx
    .rx_padding : {{
        FILL(0)
        . = ALIGN(0x1000);
    }} :payload_rx
    __patch_payload_rx_end = .;
    __patch_payload_rx_size = __patch_payload_rx_end - __patch_payload_start;

    .data : {{
        KEEP(*(.patch.link_roots))
        *(.data .data.*)
        *(.got .got.*)
    }} :payload_rw
    .bss (NOLOAD) : {{
        *(.bss .bss.*)
        *(COMMON)
        . = ALIGN(0x1000);
    }} :payload_rw
    __patch_payload_end = .;

    ASSERT(__patch_payload_rx_size > 0, "empty executable payload")
    ASSERT((__patch_payload_rx_end & 0xfff) == 0, "unaligned RX/RW boundary")
    ASSERT(__patch_payload_end < 0x08000000, "payload reaches application heap")
    /DISCARD/ : {{ *(.comment .note .note.* .eh_frame .eh_frame_hdr) }}
}}
"#,
        label = profile.program.label,
        kind = profile.name,
        app_init = contract.original_app_init,
        bootstrap = contract.bootstrap,
        room = contract.bootstrap_end - contract.bootstrap,
        payload = contract.payload,
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::PROFILES;

    #[test]
    fn every_script_places_its_program_and_router() {
        for profile in PROFILES {
            let script = linker_script(profile);
            let contract = profile.program.contract;
            assert!(script.contains(&format!("ENTRY({})\n", profile.entries()[0])));
            assert!(script.contains(&format!(
                ". = {:#010x};\n    .patch.bootstrap",
                contract.bootstrap
            )));
            assert!(script.contains(&format!(
                ". = {:#010x};\n    __patch_payload_start",
                contract.payload
            )));
            assert!(script.contains(&format!(
                "__patch_original_app_init = {:#010x};",
                contract.original_app_init
            )));
        }
        let bank = linker_script(PROFILES[0]);
        assert!(bank.contains("ENTRY(bank_offline_next)"));
        assert!(bank.contains("<= 0x6f0, \"bootstrap exceeds"));
        assert!(linker_script(PROFILES[1]).contains("<= 0xe54, \"bootstrap exceeds"));
    }
}
